const dict = { fr, en };
export type Lang = keyof typeof dict;

export function stored(key: string): string | null {
  try {
    return localStorage.getItem(key);
  } catch {
    return null;
  }
}
export function store(key: string, value: string | null) {
  try {
    if (value === null) localStorage.removeItem(key);
    else localStorage.setItem(key, value);
  } catch {
    // storage unavailable: the choice only lasts for this session
  }
}

export const i18n = $state({ lang: (stored('lang') === 'en' ? 'en' : 'fr') as Lang });

/** Title of a code rule such as "secret.github-token", or the raw id when unknown. */
export function ruleTitle(id: string): string {
  const k = `rule.${id}`;
  return k in dict[i18n.lang] ? t(k as Key) : id;
}

/** "why" or "fix" text of a code rule, or "" when the rule has none. Read raw: no plural or {param} handling. */
export function ruleHelp(id: string, part: 'why' | 'fix'): string {
  return (dict[i18n.lang] as Record<string, string>)[`rule.${id}.${part}`] ?? '';
}

export function t(k: Key, params: Record<string, string | number> = {}): string {
  let s: string = dict[i18n.lang][k];
  if (s.includes('|')) s = s.split('|')[Number(params.n) > 1 ? 1 : 0];
  return s.replace(/\{(\w+)\}/g, (_, p: string) => String(params[p] ?? ''));
}
